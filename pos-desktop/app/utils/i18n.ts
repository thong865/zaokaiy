export const DICTS: Record<Lang, Dict> = { en, lo }

export function translate(lang: Lang, key: string, params?: Record<string, string | number>): string {
  const pick = (d: unknown) => key.split('.').reduce<unknown>((o, k) => (o && typeof o === 'object' ? (o as Record<string, unknown>)[k] : undefined), d)
  let s = pick(DICTS[lang]) ?? pick(DICTS.en)
  if (typeof s !== 'string') return key
  for (const [k, v] of Object.entries(params ?? {})) s = (s as string).replaceAll(`{${k}}`, String(v))
  return s as string
}
